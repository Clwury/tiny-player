#!/usr/bin/env python3
"""Prepare the pinned libplacebo and Cargo environment for Linux development."""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys


ROOT = Path(__file__).resolve().parents[1]
CONFIG_MARKER = "# Generated by scripts/prepare-linux.py.\n"
MESON_REF = "1.9.1"


def run(*arguments: str, cwd: Path | None = None) -> None:
    subprocess.run(arguments, cwd=cwd, check=True)


def checkout(directory: Path, url: str, reference: str) -> None:
    if not (directory / ".git").is_dir():
        directory.mkdir(parents=True, exist_ok=True)
        run("git", "init", "--quiet", str(directory))
        run("git", "-C", str(directory), "remote", "add", "origin", url)
    actual_url = subprocess.check_output(
        ["git", "-C", str(directory), "remote", "get-url", "origin"], text=True,
    ).strip()
    if actual_url != url:
        raise RuntimeError(f"Unexpected source repository at {directory}: {actual_url}")
    cached = subprocess.run(
        ["git", "-C", str(directory), "rev-parse", "--verify", f"{reference}^{{commit}}"],
        capture_output=True, text=True,
    )
    if cached.returncode:
        run("git", "-C", str(directory), "fetch", "--depth", "1", "origin", reference)
        reference = "FETCH_HEAD"
    run("git", "-C", str(directory), "checkout", "--quiet", "--detach", reference)


def libplacebo_commit(root: Path) -> str:
    # Share the exact snapshot already used by the release bundle.
    source = (root / "packaging/linux/build-native.sh").read_text()
    match = re.search(r"^libplacebo_commit=([0-9a-f]{40})$", source, re.MULTILINE)
    if not match:
        raise RuntimeError("Linux packaging does not pin a libplacebo commit")
    return match[1]


def prepend_path(directory: Path, value: str) -> str:
    return os.pathsep.join(dict.fromkeys([str(directory), *filter(None, value.split(os.pathsep))]))


def cargo_config(prefix: Path, environment: dict[str, str]) -> str:
    values = {
        "PKG_CONFIG_PATH": prepend_path(prefix / "lib/pkgconfig", environment.get("PKG_CONFIG_PATH", "")),
        "LD_LIBRARY_PATH": prepend_path(prefix / "lib", environment.get("LD_LIBRARY_PATH", "")),
        "TINY_LIBPLACEBO_LIB_DIR": str(prefix / "lib"),
    }
    return CONFIG_MARKER + "[env]\n" + "".join(
        f"{name} = {{ value = {json.dumps(value, ensure_ascii=False)}, force = true }}\n"
        for name, value in values.items()
    )


def check_config_owner(config: Path) -> None:
    if config.exists() and not config.read_text().startswith(CONFIG_MARKER):
        raise RuntimeError(
            f"Preserving existing {config}; configure PKG_CONFIG_PATH and LD_LIBRARY_PATH "
            "for the prepared libplacebo manually, or move the file before preparing"
        )


def validate_headers(prefix: Path) -> None:
    config = (prefix / "include/libplacebo/config.h").read_text()
    vulkan = (prefix / "include/libplacebo/vulkan.h").read_text()
    version = re.search(r"^#define PL_API_VER\s+(\d+)", config, re.MULTILINE)
    queue = re.search(r"struct pl_vulkan_queue\s*\{(.*?)\};", vulkan, re.DOTALL)
    if not version or int(version[1]) < 365 or not queue or not re.search(r"\bflags\s*;", queue[1]):
        raise RuntimeError(f"{prefix} lacks libplacebo API 365 queue creation flags")


def prepared(prefix: Path, commit: str) -> bool:
    try:
        if (prefix / "libplacebo.commit").read_text().strip() != commit:
            return False
        validate_headers(prefix)
        return (prefix / "lib/libplacebo.so").is_file() and (prefix / "lib/pkgconfig/libplacebo.pc").is_file()
    except (OSError, RuntimeError):
        return False


def prepare(root: Path, jobs: int) -> Path:
    config = root / ".cargo/config.toml"
    check_config_owner(config)
    native = root / "target/linux-native"
    prefix = native / "prefix"
    commit = libplacebo_commit(root)
    stamp = prefix / "libplacebo.commit"
    if not prepared(prefix, commit):
        for program in ["git", "ninja", "pkg-config", "cc"]:
            if not shutil.which(program):
                raise RuntimeError(f"Install {program} before preparing Linux dependencies")
        run("pkg-config", "--exists", "vulkan", "shaderc", "lcms2")
        source = native / "src/libplacebo"
        checkout(source, "https://github.com/haasn/libplacebo.git", commit)
        run("git", "-C", str(source), "submodule", "update", "--init", "--depth", "1", "3rdparty/fast_float")
        meson = shutil.which("meson")
        if meson:
            meson_command = [meson]
        else:
            meson_source = native / "src/meson"
            checkout(meson_source, "https://github.com/mesonbuild/meson.git", MESON_REF)
            meson_command = [sys.executable, str(meson_source / "meson.py")]
        build = native / "build/libplacebo"
        setup = [*meson_command, "setup", str(build), str(source)]
        if (build / "meson-private/coredata.dat").exists():
            setup.append("--reconfigure")
        run(
            *setup, f"--prefix={prefix}", "--libdir=lib", "--buildtype=release",
            "--default-library=shared", "--wrap-mode=nofallback",
            "-Dvulkan=enabled", "-Dshaderc=enabled", "-Dglslang=disabled",
            "-Dopengl=disabled", "-Dd3d11=disabled", "-Dlcms=enabled",
            "-Ddovi=enabled", "-Dlibdovi=disabled", "-Dunwind=disabled",
            "-Dxxhash=disabled", "-Ddemos=false", "-Dtests=false",
        )
        run(*meson_command, "compile", "-C", str(build), "-j", str(jobs))
        run(*meson_command, "install", "-C", str(build), "--no-rebuild")
        validate_headers(prefix)
        stamp.write_text(commit + "\n")
    validate_headers(prefix)
    config.parent.mkdir(parents=True, exist_ok=True)
    config.write_text(cargo_config(prefix, dict(os.environ)))
    return prefix


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--jobs", type=int, default=4, help="Native build jobs (default: 4)")
    args = parser.parse_args()
    if not sys.platform.startswith("linux"):
        parser.error("this preparation command requires Linux")
    if args.jobs < 1:
        parser.error("--jobs must be positive")
    try:
        prefix = prepare(ROOT, args.jobs)
    except (OSError, RuntimeError, subprocess.CalledProcessError) as error:
        parser.exit(1, f"Linux dependency preparation failed: {error}\n")
    print(f"Prepared libplacebo at {prefix}")
    print("Cargo now uses matching headers and runtime libraries. Run cargo run --locked.")


if __name__ == "__main__":
    main()
